"""Step 3 (single serial HEAVY job): the physical releases of the gain sweep.

Budget, frozen in PREREGISTRATION.json:
  4 gains x 5 release phases at 0.5 ms with the MOTOR-CELL ridge readout   = 20
  the best-information gain x 5 phases with the WHOLE-POPULATION readout   =  5
  the top-two gains x 5 phases at 0.0625 ms with the motor-cell readout    = 10
  total releases = 35 (cap 35); warms = 4 already done at 0.5 ms + 2 at 0.0625 ms; teacher
  recordings = 0.

Every release starts from that gain own warm state, applies the RH excitatory gain .375 exactly
once, and writes ctrl only: qfrc_applied and xfrc_applied stay identically zero, nothing is
assisted and no pose is written.  The neurons generate the command.
"""
