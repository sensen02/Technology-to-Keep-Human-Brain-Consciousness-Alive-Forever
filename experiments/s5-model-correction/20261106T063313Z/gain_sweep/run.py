def no_other_heavy_job():
    out = subprocess.run(['pgrep', '-af', 'python'], capture_output=True, text=True).stdout
    me = __import__('os').getpid()
    others = []
    for line in out.splitlines():
        parts = line.split(None, 1)
        if len(parts) != 2:
            continue
        if int(parts[0]) == me:
            continue
        try:
            argv0 = __import__('pathlib').Path(f'/proc/{parts[0]}/cmdline').read_bytes().split(b'\0')[0].decode()
        except OSError:
            continue
        if 'python' not in __import__('pathlib').Path(argv0).name:
            continue
        if any(k in parts[1] for k in ('gain_sweep', 'pop_readout', 'readout_fit/run.py',
                                       'numerics/run.py', 'fine_phase', 'physical_phase',
                                       'numerics_shift', 'numerics_chaos')):
            others.append(line)
    assert not others, 'another heavy job is running: %r' % (others,)
    return dict(pgrep_lines=[l for l in out.splitlines() if 'python' in l], others=others)


def cleanup_constructor_output():
    """The legacy constructor rewrites O/COVERAGE.json on every import; log and delete it."""
    p = C.O / 'COVERAGE.json'
    if not p.exists():
        return
    ledger = C.O / 'CLEANUP_LEDGER.json'
    v = js(ledger) if ledger.exists() else {'deleted': []}
    v['deleted'].append(dict(
        path=str(p), sha256=sha(p), bytes=p.stat().st_size, importance='可再生临时',
        reason='Regenerated by the legacy Trial constructor on every construction. Pool and '
               'sign-matrix identities are recorded in this task RELEASE_IDENTITIES.json; no '
               'result depends on this file. The legacy write target was redirected into this '
               'task output directory and the regenerated copy is deleted here.'))
    dump(ledger, v)
    p.unlink()


class SweepRuntime(rt.b.Trial):
    """Physical release loop with the scaled sensory encoder and a pluggable ridge readout."""

    def __init__(self):
        rt.O = C.O
        rt.b.O = C.O
        rt.b.Trial.__init__(self)
        cleanup_constructor_output()
        self.cells = C.motor_cells_204()
        self.history = SpikeHistory(self.cells, dt=C.DT_MAIN)
        self.neural_dt = C.DT_MAIN
        self.n = round(C.CDT / C.DT_MAIN)
        self.cache = {}
        self.set_dt(C.DT_MAIN)
        self.gain = C.REF_GAIN
        self.enc = ChannelSensoryEncoder(self.groups, 12000,
                                         ChannelConfig(current_nA_per_unit=self.gain))
        self.readout = None
        legs, legcells, rh = C.leg_cells_and_rh()
        self.rh = rh
        self.legcells = legcells
        dump(C.O / 'RELEASE_IDENTITIES.json', dict(
            cells=self.cells, RH_cells=self.rh, limits=self.limits,
            pools=[p.tolist() for p in self.pools],
            joint_names=[self.m.joint(int(j)).name for j in self.jids],
            RH_gain_at_release=C.RH_GAIN,
            encoder_gain_nA_per_unit=self.gain,
            readout_feature='5 ms-filtered per-cell rates at the 1 ms interval start',
            importance='核心必需'))
        # the gain-scaled encoder must reproduce the sealed encoder's group partition
        with C.PHYSICAL.open('rb') as f:
            sealed_enc = pickle.load(f)[1.3]['enc']
        same = all(np.array_equal(np.asarray(self.enc.groups[leg][ch], int),
                                  np.asarray(sealed_enc.groups[leg][ch], int))
                   for leg in sealed_enc.groups for ch in sealed_enc.groups[leg])
        self.encoder_partition_matches_sealed = bool(same)
        assert same, 'the gain-scaled encoder changed the channel partition'

    def set_gain(self, gain):
        self.gain = float(gain)
        self.enc.cfg.current_nA_per_unit = self.gain

    def set_dt(self, dt):
        self.neural_dt = dt
        self.n = round(C.CDT / dt)
        assert abs(self.n * dt - C.CDT) < 1e-15
        self.decay = float(np.exp(-dt / C.FILTER_TAU))
        self.history = SpikeHistory(self.cells, dt=dt)

    def integrate(self, net, current, rates, cell):
        assert net.dt == self.neural_dt * 1000
        counts = np.zeros(12000, np.int32)
        self.last_spikes = []
        self.last_full = []
        for _ in range(self.n):
            sp = net.step(current_nA=current)
            counts += sp
            self.last_full.append(np.packbits(sp))
            self.last_spikes.append(sp[self.cells].copy())
            self.history.consume(sp)
            rates = self.decay * rates + (1 - self.decay) * np.asarray(self.poolmat @ sp,
                                                                     float) / self.neural_dt
            cell = self.decay * cell + (1 - self.decay) * np.asarray(sp, float) / self.neural_dt
        return rates, cell, counts, current

    def observe_neural(self, d, net, rates, cell):
        from run_neural_muscle_closure import observe_quantities
        current = np.asarray(self.enc.encode(observe_quantities(self.m, d, self.q0, self.joints,
                                                                self.geom))[0])
        return self.integrate(net, current, rates, cell)

    def command(self, cell):
        """Motor-cell or whole-population ridge readout, clipped to the sealed joint limits."""
        ro = self.readout
        feats = cell if ro['cells'] is None else cell[ro['cells']]
        raw = ro['W'] @ (feats - ro['mean_fit']) + ro['b']
        return raw, np.clip(raw, -self.limits, self.limits)

    def episode(self, label, ph, readout_name):
        import train_dynamic_support as dst
        import dynamic_support_metrics as dsm
        folder = C.O / 'RUNS' / label
        folder.mkdir(parents=True, exist_ok=False)
        dump(folder / 'PREREGISTRATION.json', dict(
            label=label, gain_nA_per_unit=self.gain, readout=readout_name,
            parent=str(C.O / 'PREREGISTRATION.json'),
            parent_sha256=sha(C.O / 'PREREGISTRATION.json'),
            release_time_s=ph, duration_s=C.DURATION, neural_dt_s=self.neural_dt,
            neural_steps_per_command=self.n, command_dt_s=C.CDT, physics_dt_s=C.PHYSICS_DT,
            history_dt_s=self.history.dt, actor='identically zero; no translator',
            RH_exc_gain=C.RH_GAIN, cut=False, sensory_cut=False,
            qfrc_applied='identically zero', xfrc_applied='identically zero',
            external_force='none', pose_write='none',
            warm_cache=str(C.O / 'CONFIGS' / (C.gain_tag(self.gain) + '__' +
                                              C.dt_tag(self.neural_dt)) / 'WARM_CACHE.pkl'),
            readout_rule='clip(W @ (%s - mean_fit) + b, +/- limits), W/b fitted on the '
                         '0.2-0.8 s teacher window of this same gain at 0.5 ms'
                         % ('r_12000' if self.readout['cells'] is None else 'r_204'),
            readout_source=self.readout.get('source'),
            readout_source_sha256=self.readout.get('source_sha256'),
            readout_r2_held=self.readout['r2_held'],
            importance='核心必需'))
        c = self.cache[ph]
        net = copy.deepcopy(c['net'])
        rates = c['rates'].copy()
        cell = c['cell'].copy()
        self.history.load_state_dict(c['history'])
        rowids = np.repeat(np.arange(net.n), np.diff(net.We.indptr))
        net.We.data[np.isin(rowids, self.rh)] *= C.RH_GAIN
        d = self.mj.MjData(self.m)
        self.mj.mj_setState(self.m, d, c['integration'], self.mj.mjtState.mjSTATE_INTEGRATION)
        self.mj.mj_forward(self.m, d)
        q = d.qpos.copy()
        v = d.qvel.copy()
        d.ctrl[:] = self.command(cell)[1]
        d.qfrc_applied[:] = 0
        d.xfrc_applied[:] = 0
        self.mj.mj_forward(self.m, d)
        assert np.array_equal(q, d.qpos) and np.array_equal(v, d.qvel)
        body = [self.bodyrow(d)]
        native = [self.contact(d)]
        logs = []
        cur0 = None
        start = time.monotonic()
        try:
            for k in range(round(C.DURATION / C.CDT)):
                features = self.history.features()
                raw, ctrl = self.command(cell)
                source = rates.copy()
                rates, cell, counts, cur = self.observe_neural(d, net, rates, cell)
                if k == 0:
                    cur0 = cur.copy()
                d.ctrl[:] = ctrl
                for j in range(80):
                    assert not d.qfrc_applied.any() and not d.xfrc_applied.any()
                    self.mj.mj_step(self.m, d)
                    self.mj.mj_forward(self.m, d)
                    native.append(self.contact(d))
                    assert np.isfinite(d.qpos).all() and np.isfinite(d.qvel).all()
                    assert not d.warning.number.any()
                    if (j + 1) % 40 == 0:
                        body.append(self.bodyrow(d))
                logs.append(dict(time=float(d.time), features=features, source_rates=source,
                                 rates=rates.copy(), raw_command=raw, applied=ctrl,
                                 spikes204=np.asarray(self.last_spikes),
                                 spikes12000_packed=np.asarray(self.last_full),
                                 sensory_current_norm=float(np.linalg.norm(cur)),
                                 sensory_current_max_abs=float(np.abs(cur).max()),
                                 net_t_ms=net.t_ms, net_steps=net.steps))
            arr = np.asarray(native)
            scored = arr.copy()
            scored[:, 0] -= ph - 1.3
            prior = dst.RELEASE
            dst.RELEASE = C.DURATION
            try:
                J, parts = dst.objective(scored, c['assist'])
            finally:
                dst.RELEASE = prior
            gate = dsm.evaluate_native(c['assist'], arr)
            gate['checks']['D1_no_nonfoot_ground_force'] = bool(np.max(arr[:, 7]) == 0)
            gate['passed'] = all(gate['checks'].values())
            pos = np.flatnonzero(arr[:, 7] > 1e-9)
            applied = np.asarray([r['applied'] for r in logs])
            sat = np.abs(np.abs(applied) - self.limits[None, :]) < 1e-12
            result = dict(
                label=label, gain_nA_per_unit=self.gain, readout=readout_name,
                dt_s=self.neural_dt, release_time_s=ph, duration_s=C.DURATION,
                J=J, parts=parts, validation=gate,
                first_positive_nonfoot_s=float(arr[pos[0], 0] - ph) if len(pos) else None,
                wall_s=time.monotonic() - start,
                peak_rss_MiB=resource.getrusage(resource.RUSAGE_SELF).ru_maxrss / 1024,
                warnings=int(d.warning.number.sum()),
                release_aux_max=float(np.max(np.abs(arr[:, -1]))),
                release_external_max=0., walking_certified=False,
                applied_command_rms=float(np.sqrt((applied ** 2).mean())),
                applied_saturation_fraction=float(sat.mean()),
                readout_r2_held=float(self.readout['r2_held']),
                folder=str(folder), importance='核心必需')
            dump(folder / 'RESULT.json', result)
        except BaseException:
            import traceback
            dump(folder / 'FAILURE.json', dict(traceback=traceback.format_exc()))
            raise
        finally:
            np.savez_compressed(folder / 'NATIVE.npz', rows=np.asarray(native))
            if cur0 is not None:
                np.savez_compressed(folder / 'SENSORY_FIRST.npz', current_first_interval=cur0,
                                    note='injected sensory current at the first release '
                                         'interval; the physical state there is gain-independent, '
                                         'so this must equal the 0.3 vector times gain/0.3')
            np.savez_compressed(folder / 'BODY.npz',
                                **{k: np.array([r[k] for r in body]) for k in body[0]})
            if logs:
                np.savez_compressed(folder / 'NEURAL.npz',
                                    **{k: np.array([r[k] for r in logs]) for k in logs[0]})
        print('RELEASE %-34s gain=%-5g J=%.4f pass=%s D=%s/8 wall=%.1fs' %
              (label, self.gain, J, gate['passed'],
               sum(gate['checks'].values()), result['wall_s']), flush=True)
        return result


def load_readout(folder, name):
    z = C.arrays(folder / name)
    return dict(W=z['W'], b=z['b'], mean_fit=z['mean_fit'],
                cells=(None if 'cells' not in z else np.asarray(z['cells'], int)),
                alpha=float(z['alpha'][0]), gamma=float(z['gamma'][0]),
                r2_fit=float(z['r2_fit'][0]), r2_held=float(z['r2_held'][0]))


def main():
    C.O.mkdir(parents=True, exist_ok=True)
    free = no_other_heavy_job()
    for name in ('PREREGISTRATION.json', 'STATIC_CHECKS.json', 'GAIN_METRICS_OFFLINE.json',
                 'RANKING.json'):
        assert (C.O / name).exists(), 'missing ' + name
    assert js(C.O / 'STATIC_CHECKS.json')['all_passed']
    before = js(C.O / 'INPUT_HASHES_BEFORE.json')
    assert {p: sha(p) for p in before} == before, 'a sealed input changed before the heavy job'
    freeze = js(C.O / 'SOURCE_FREEZE.json')['files']
    fixes = {f['path']: f for f in js(C.O / 'CHANGE_LEDGER.json').get('tool_fixes', [])}
    declared = {}
    for p, h in freeze.items():
        now = sha(p)
        if now == h:
            continue
        fx = fixes.get(p)
        assert fx is not None and fx.get('old_sha256') == h and fx.get('new_sha256') == now, \
            'the frozen source changed without a declared fix: %s' % p
        declared[p] = dict(frozen_sha256=h, current_sha256=now, reason=fx['reason'])
    dump(C.O / 'DECLARED_SOURCE_FIXES_USED.json', dict(declared=declared,
                                                       preflight_pgrep=free))
    ranking = js(C.O / 'RANKING.json')

    t = SweepRuntime()
    rows = []
    progress = []

    def run_block(gain, dt, readout_name, readout_zip, phases):
        fitfolder = C.O / 'CONFIGS' / (C.gain_tag(gain) + '__dt_0p5ms')
        cfgfolder = C.O / 'CONFIGS' / (C.gain_tag(gain) + '__' + C.dt_tag(dt))
        t.set_gain(gain)
        t.set_dt(dt)
        t.readout = load_readout(fitfolder, readout_zip)
        t.readout['source'] = str(fitfolder / readout_zip)
        t.readout['source_sha256'] = sha(fitfolder / readout_zip)
        if not (cfgfolder / 'WARM_CACHE.pkl').exists():
            F.CAP['%g' % gain] = {}
            F.warm(gain, dt, None, t.cells, t.poolmat)
        with (cfgfolder / 'WARM_CACHE.pkl').open('rb') as f:
            t.cache = pickle.load(f)
        done = []
        for ph in phases:
            label = 'g%s__%s__%s__rel_%s' % (C.gain_tag(gain)[5:], C.dt_tag(dt),
                                             readout_name.replace('_', ''), ph)
            r = t.episode(label, ph, readout_name)
            r['gain_tag'] = C.gain_tag(gain)
            r['dt_tag'] = C.dt_tag(dt)
            r['readout_name'] = readout_name
            rows.append(r)
            done.append(dict(label=label, J=r['J'], D_passed=r['validation']['passed'],
                             D_count=int(sum(r['validation']['checks'].values()))))
            progress.append(dict(gain=gain, dt_s=dt, readout=readout_name,
                                 release_time_s=ph, J=r['J'],
                                 D_passed=r['validation']['passed']))
            dump(C.O / 'PROGRESS.json', dict(releases=progress, count=len(progress)))
        del t.cache
        t.cache = {}
        return done

    blocks = {}
    # (1) all four gains, motor-cell readout, 0.5 ms
    for gain in C.GAINS:
        blocks['%s|%s|motor204' % (C.gain_tag(gain), C.dt_tag(C.DT_MAIN))] = run_block(
            gain, C.DT_MAIN, 'motor204', 'READOUT_MOTOR204.npz', C.PHASES)
    # (2) the single best-information gain, whole-population readout, 0.5 ms
    best = float(ranking['whole_population_release_gain'])
    blocks['%s|%s|all12000' % (C.gain_tag(best), C.dt_tag(C.DT_MAIN))] = run_block(
        best, C.DT_MAIN, 'all12000', 'READOUT_ALL12000.npz', C.PHASES)
    # (3) the top-two gains at the second timestep, motor-cell readout
    for gain in ranking['second_timestep_gains']:
        gain = float(gain)
        blocks['%s|%s|motor204' % (C.gain_tag(gain), C.dt_tag(C.DT_FINE))] = run_block(
            gain, C.DT_FINE, 'motor204', 'READOUT_MOTOR204.npz', C.PHASES)

    assert len(rows) <= C.MAX_RELEASES, len(rows)
    warm_count = len(sorted(p for p in (C.O / 'CONFIGS').glob('*') if p.is_dir()))
    dump(C.O / 'RELEASE_SUMMARY.json', dict(
        blocks=blocks, releases=len(rows), warms=warm_count,
        preflight_pgrep=free, row_level=rows,
        teacher_recordings=0, importance='核心必需'))
    after = {p: sha(p) for p in before}
    assert after == before, 'a sealed input changed during the heavy job'
    dump(C.O / 'INPUT_HASHES_AFTER.json', after)
    print('DONE releases=%d warms=%d' % (len(rows), warm_count), flush=True)


if __name__ == '__main__':
    try:
        main()
    except BaseException:
        import traceback
        C.O.mkdir(parents=True, exist_ok=True)
        dump(C.O / ('FAILURE_run_' + str(time.time_ns()) + '.json'),
             dict(traceback=traceback.format_exc()))
        raise
