"""Delivery: file inventory with importance labels, manifest with a self-audit, ledger check.

Run last, after REPORT.zh-CN.md is written.  Writes nothing outside this task output dir.
"""
import hashlib
import json
from pathlib import Path

import common as C

CORE = '核心必需'
AUX = '重要辅助'
TEMP = '可再生临时'
UNKNOWN = '待确认'

EXPLICIT = {
    'PREREGISTRATION.json': (CORE, 'pre-registered design, reading rule, amendments, abort conditions'),
    'AMENDMENT_APPLIED.json': (CORE, 'record that A1-A4 were applied before any physical release'),
    'INPUT_HASHES_BEFORE.json': (CORE, 'hashes of every sealed read-only input'),
    'INPUT_HASHES_AFTER.json': (CORE, 're-hash after the heavy job; must equal BEFORE'),
    'CHANGE_LEDGER.json': (CORE, 'old/new hashes and reasons for every change, incl. the amendments'),
    'SOURCE_FREEZE.json': (CORE, 'frozen source hashes, extended to the analysis tools before the run'),
    'TRANSLATOR_IDENTITIES.json': (CORE, 'decoder identity actually used (42x66 matrix, 42 limits)'),
    'READOUT_FIT.npz': (CORE, 'fitted readouts: W/b for P1, P2, P3 plus the diagnostics'),
    'READOUT_DESCRIPTION.json': (CORE, 'JSON description of the fitted readouts and their rules'),
    'READOUT_STATIC.json': (CORE, 'interface statistics, CV curves, shuffle control, stability'),
    'CELL_ANNOTATION.json': (CORE, 'banc_888_id join, top-50 cells and weight-mass category shares'),
    'CLOSEDLOOP_TRACKING.json': (CORE, 'command vs teacher torque over 20/50/100/200 ms of the release'),
    'R0_BITWISE.json': (CORE, 'bitwise comparison of the 10 reproduced R0 control releases'),
    'SUMMARY.json': (CORE, 'all per-phase outcomes, spreads and the pre-registered verdict'),
    'VERIFICATION.json': (CORE, 'independent verification of every claim'),
    'FIGURE_pop_readout.png': (CORE, 'per phase x timestep J / foot support / min COM / D count'),
    'FIGURE_OBSERVATION.md': (CORE, 'what was actually seen when the figure was opened'),
    'REPORT.zh-CN.md': (CORE, 'Chinese report'),
    'FILE_INVENTORY.json': (CORE, 'this inventory with importance labels'),
    'MANIFEST_SHA256.json': (CORE, 'hashes of every deliverable plus a self-audit'),
    'CLEANUP_LEDGER.json': (CORE, 'records of deleted regenerated files'),
    'DECLARED_SOURCE_FIXES_USED.json': (CORE, 'every deviation of the run source from the pre-run '
                                       'freeze, each bridged by CHANGE_LEDGER.tool_fixes'),
    'PROGRESS.json': (AUX, 'per-release progress log, overwritten as the job advanced'),
    'COVERAGE.json': (TEMP, 'regenerated by the legacy constructor; should be deleted, see ledger'),
}


def classify(rel):
    if rel in EXPLICIT:
        return EXPLICIT[rel]
    p = rel.replace('\\', '/')
    if p.startswith('PREAMENDMENT/'):
        return (AUX, 'pre-amendment fit artifacts, kept unchanged as the evidence for amendments A1-A4')
    if p.startswith('RUNS/'):
        name = p.rsplit('/', 1)[-1]
        if name in ('RESULT.json', 'NATIVE.npz'):
            return (CORE, 'release result / 12.5 us native contact record')
        if name in ('BODY.npz', 'NEURAL.npz'):
            return (AUX, 'full body and neural trace of one release, retained for re-analysis')
        if name == 'PREREGISTRATION.json':
            return (AUX, 'per-release record of the exact readout and clock used')
        if name == 'FAILURE.json':
            return (CORE, 'failure record')
    if p.startswith('LOGS/'):
        return (TEMP, 'run log')
    if p.startswith('FAILURE'):
        return (CORE, 'failure record')
    if p.startswith('CELL_FILTER_CHECK_'):
        return (CORE, 'proof the runtime 5 ms cell filter reproduces the sealed warm trace')
    return (UNKNOWN, 'not classified by this task')


def digest_entries(entries):
    h = hashlib.sha256()
    for e in entries:
        h.update((e['relative_path'] + '\0' + e['sha256'] + '\0' + str(e['bytes']) + '\n').encode())
    return h.hexdigest()


SELF = ('FILE_INVENTORY.json', 'CLEANUP_LEDGER.json', 'MANIFEST_SHA256.json')


def scan(skip_manifest=True):
    out = []
    for f in sorted(C.O.rglob('*')):
        if not f.is_file():
            continue
        if skip_manifest and f.name == 'MANIFEST_SHA256.json':
            continue
        rel = str(f.relative_to(C.O))
        imp, use = classify(rel)
        out.append(dict(relative_path=rel, absolute_path=str(f), bytes=f.stat().st_size,
                        sha256=C.sha(f), importance=imp, purpose=use))
    return out


def main():
    first = scan()
    counts = {}
    for e in first:
        counts[e['importance']] = counts.get(e['importance'], 0) + 1
    src = [dict(absolute_path=str(p), bytes=p.stat().st_size, sha256=C.sha(p),
                importance=CORE, purpose='frozen experiment source')
           for p in sorted(C.SRC.glob('*.py'))]
    C.dump(C.O / 'FILE_INVENTORY.json', dict(
        output_dir=str(C.O), source_dir=str(C.SRC), files=first, source_files=src,
        importance_counts=counts,
        labels=dict(核心必需='core deliverable, required to read or reproduce the result',
                    重要辅助='supporting evidence retained for re-analysis',
                    可再生临时='regenerated during the run; safe to delete',
                    待确认='not classified by this task; kept untouched'),
        cleaned='COVERAGE.json is regenerated by the legacy Trial constructor on every import; each '
                'regenerated copy was deleted and recorded in CLEANUP_LEDGER.json',
        self_reference='FILE_INVENTORY.json and CLEANUP_LEDGER.json are written by this delivery '
                       'step, so their own hashes below are the pre-write values; '
                       'MANIFEST_SHA256.json records their final hashes.',
        note='Absolute paths only; nothing was written into a sealed read-only directory, into '
             'engine/, or into GOAL_TRACKER.zh-CN.md.'))

    ledger = C.js(C.O / 'CLEANUP_LEDGER.json') if (C.O / 'CLEANUP_LEDGER.json').exists() \
        else {'deleted': []}
    ledger['kept'] = [dict(path=e['absolute_path'], importance=e['importance'],
                           purpose=e['purpose'])
                      for e in first if e['relative_path'] not in SELF]
    ledger['not_cleaned_reason'] = (
        'No superseded or duplicate deliverable was produced: every release folder is one distinct '
        'cell of the pre-registered 4x5x2 grid, and every intermediate array feeds the '
        'verification, the tracking diagnostic or the figure. The only regenerated file '
        '(COVERAGE.json) is deleted on every constructor call. Every log under LOGS/ is regenerable '
        'by re-running the corresponding stage, so they are labelled 可再生临时; the pre-amendment '
        'fit log is kept separately under PREAMENDMENT/.')
    ledger['self_reference'] = 'This ledger is written by the delivery step; its own final hash is ' \
                               'in MANIFEST_SHA256.json, not here.'
    C.dump(C.O / 'CLEANUP_LEDGER.json', ledger)

    final = scan()
    ok_inputs = C.js(C.O / 'INPUT_HASHES_BEFORE.json') == C.js(C.O / 'INPUT_HASHES_AFTER.json')
    freeze = C.js(C.O / 'SOURCE_FREEZE.json')['files']
    led = C.js(C.O / 'CHANGE_LEDGER.json')
    fixes = {f['path']: f for f in led.get('tool_fixes', [])}
    now_src = {p: C.sha(p) for p in freeze}
    undeclared, bad_fix = [], []
    for p in freeze:
        if freeze[p] != now_src[p]:
            fx = fixes.get(p)
            if fx is None or fx.get('old_sha256') != freeze[p] or fx.get('new_sha256') != now_src[p]:
                undeclared.append(p)
    for p, fx in fixes.items():
        if p in now_src and fx.get('new_sha256') is not None and now_src[p] != fx['new_sha256']:
            bad_fix.append(p)
    ok_source = bool(not undeclared and not bad_fix)
    a = {e['relative_path']: e['sha256'] for e in first if e['relative_path'] not in SELF}
    b = {e['relative_path']: e['sha256'] for e in final if e['relative_path'] not in SELF}
    verified = json.loads((C.O / 'VERIFICATION.json').read_text())
    manifest = dict(
        output_dir=str(C.O), source_dir=str(C.SRC),
        algorithm='sha256', files=final,
        self_audit=dict(
            file_count=len(final), total_bytes=int(sum(e['bytes'] for e in final)),
            manifest_hashes_itself=False,
            reason='A file cannot contain its own digest; instead the manifest attests the digest '
                   'of its own entry list, which any reader can recompute. Only '
                   'MANIFEST_SHA256.json itself is excluded from its own list.',
            entry_digest=digest_entries(final),
            double_read_stable=bool(a == b),
            double_read_note='Two independent hash passes over every file except the files this '
                             'step writes (FILE_INVENTORY.json, CLEANUP_LEDGER.json) and the '
                             'manifest itself.',
            second_pass_entry_count=len(b),
            experiment_source_unchanged=bool(ok_source),
            declared_tool_fixes=sorted(Path(p).name for p in fixes),
            undeclared_source_changes=undeclared,
            sealed_inputs_unchanged=bool(ok_inputs),
            verification_passed=bool(verified['verified']),
            verification_checks='%d/%d' % (verified['passed'], verified['total']),
            importance_counts=dict(counts),
            complete=bool(ok_source and ok_inputs and a == b and verified['verified']),
            complete_criterion='sealed inputs unchanged AND every source file bit-identical to the '
                               'pre-run freeze except declared amendments/tool additions AND a '
                               'stable double read AND the independent verification passed.',
        ),
        note='Every path is absolute. No sealed input, no engine/ file and no GOAL_TRACKER file '
             'was modified.')
    C.dump(C.O / 'MANIFEST_SHA256.json', manifest)
    print('DELIVERED', len(final), 'files', counts,
          'complete', manifest['self_audit']['complete'],
          'stable', manifest['self_audit']['double_read_stable'], flush=True)


if __name__ == '__main__':
    main()
