"""Conditional teacher targets only: no physical state writes or extra forces.

Call pin_baseline() before importing baseline modules in a fresh process. Existing
imports from a different lineage are rejected, not silently relabelled.
"""
from pathlib import Path
import sys
import numpy as np

BASELINE = Path('/run/media/sensen/Data2/cell_wound_prototype/experiments/banc-walking-recovery/20261110T152714Z')


def pin_baseline():
    for name in ('physics', 'static_teacher', 'wave_reference', 'models', 'student_wave', 'identity', 'cycle_reward'):
        if name in sys.modules:
            actual = Path(sys.modules[name].__file__).resolve()
            if actual != BASELINE / (name + '.py'):
                raise RuntimeError(f'Conflicting absolute import {name}: {actual}')
    sys.path.insert(0, str(BASELINE))


class ConditionalTwistReference:
    """Wrap baseline WaveReference. Clock and command schedule are TEACHER ONLY.

    speed_scale in [0,1] slows the whole measured gait, preserving swing shape.
    yaw_rate is requested rad/native second, not measured achieved yaw. Stance
    inverse twist is generated by offset_x*(ex+curvature*J*rest_xy). Baseline
    speed .075 is .36/(6*.8). Measured lateral swing offsets are preserved.
    Acceleration/deceleration use phase integral with a smooth one-second ramp.
    For variable commands construct schedules externally in a new preregistration;
    this object intentionally binds one fixed post-prime command.
    """
    def __init__(self, base, speed_scale=1., yaw_rate=0., prime_s=4.8, ramp_s=1.):
        if not np.isfinite([speed_scale, yaw_rate, prime_s, ramp_s]).all() or not 0 <= speed_scale <= 1 or prime_s < 0 or ramp_s <= 0:
            raise ValueError('Finite speed scale [0,1], prime>=0, ramp>0 required')
        if speed_scale == 0 and yaw_rate != 0:
            raise ValueError('This teacher does not implement turning in place')
        self.base, self.speed_scale, self.yaw_rate = base, float(speed_scale), float(yaw_rate)
        self.prime_s, self.ramp_s = float(prime_s), float(ramp_s)
        self.rest = np.array(base.rest_body_feet[:, :2], copy=True)
        self.curvature = 0. if speed_scale == 0 else yaw_rate / (.075 * speed_scale)
        self.metadata = dict(label='algorithm teacher conditional body-frame foot twist', speed_scale=speed_scale,
                             requested_yaw_rate=yaw_rate, curvature=self.curvature, prime_s=prime_s, ramp_s=ramp_s,
                             physical_root_writes=False, extra_forces=False)

    def command(self, elapsed_s):
        dt = max(0., float(elapsed_s)-self.prime_s)
        u = min(dt/self.ramp_s, 1.)
        blend = u*u*(3.-2.*u)
        integral = self.ramp_s*(u**3-.5*u**4) + max(0., dt-self.ramp_s)
        phase = float(elapsed_s)+(self.speed_scale-1.)*integral
        scale = 1.+(self.speed_scale-1.)*blend
        return phase, scale, self.curvature*blend

    def sample(self, elapsed_s):
        phase, scale, curvature = self.command(elapsed_s)
        sample = self.base.sample(phase)
        delta = sample['target_xy']-self.rest
        tangent = np.column_stack([-self.rest[:, 1], self.rest[:, 0]])
        sample['target_xy'] = sample['target_xy'] + curvature*delta[:, :1]*tangent
        # These derivatives are diagnostic only: StaticTeacher uses finite q_des
        # differences. Include curvature ramp derivative for contract correctness.
        u = np.clip((elapsed_s-self.prime_s)/self.ramp_s, 0., 1.)
        curvature_dot = self.curvature*6.*u*(1.-u)/self.ramp_s
        base_velocity = sample['velocity_xy'].copy()*scale
        sample['velocity_xy'] = base_velocity + (curvature*base_velocity[:, :1]+curvature_dot*delta[:, :1])*tangent
        sample['velocity_z'] = sample['velocity_z']*scale
        return sample


def make_teacher(core, *, speed_scale=1., yaw_rate=0., prime_s=4.8):
    pin_baseline()
    from static_teacher import StaticTeacher
    from student_wave import teacher_config
    teacher = StaticTeacher(core, teacher_config(100))
    teacher.reference = ConditionalTwistReference(teacher.reference, speed_scale, yaw_rate, prime_s)
    teacher.metadata['conditional_twist'] = teacher.reference.metadata
    return teacher
