"""Qualify observed loss and alternate support on an immutable paired floor run."""
import argparse
from pathlib import Path

import numpy as np

from physical import RF,RM,RM_JOINTS,RF_JOINTS,W,read,stan


def trace_of(output):
    result=read(output/'RESULT.json')
    trace=np.load(output/'TRACE.npz',allow_pickle=False)
    np.testing.assert_equal(stan.sha(output/'TRACE.npz'),result['trace_sha256'])
    audit=read(output/'NATIVE_AUDIT.json')
    np.testing.assert_equal(stan.sha(output/'NATIVE_AUDIT.json'),result['native_audit_sha256'])
    np.testing.assert_equal(stan.sha(output/'NATIVE.npz'),audit['native_sha256'])
    native=np.load(output/'NATIVE.npz',allow_pickle=False)
    decision=np.load(output/'DECISIONS.npz',allow_pickle=False)
    np.testing.assert_equal(stan.sha(output/'DECISIONS.npz'),result['decision_sha256'])
    return result,trace,audit,native,decision


def first_persistent(mask,width,start=0):
    values=np.asarray(mask[start:],dtype=np.int32)
    if len(values)<width:
        return None
    total=np.r_[0,np.cumsum(values)]
    starts=np.flatnonzero(total[width:]-total[:-width]==width)
    return int(start+starts[0]) if len(starts) else None


def compare(run,control,filled,ablation,*,role='teacher'):
    r,z,a,n,d=trace_of(run)
    c,cz,ca,cn,cd=trace_of(control)
    f,fz,fa,fn,fd=trace_of(filled)
    b,bz,ba,bn,bd=trace_of(ablation)
    assert c['scenario']==r['scenario']==b['scenario'] and not c['scenario']['filled']
    assert f['scenario']['filled'] and f['scenario']['opening']==r['scenario']['opening']
    ax,bx,ay,by=r['scenario']['opening']
    action=d['action']-d['base']
    active=np.any(np.abs(action)>1e-11,axis=1)
    if not active.any():
        raise ValueError('No enacted recovery or support command')
    first_i=int(np.flatnonzero(active)[0])
    first_ms=int(d['ms'][first_i])
    first=first_ms*80
    traj=z['rf_pad_xyz']
    inside=(traj[:,0]>ax)&(traj[:,0]<bx)&(traj[:,1]>ay)&(traj[:,1]<by)
    hz=n['rf_pad_bottom_z']
    forces=n['forces']
    rf=forces[:,RF]/W
    helper=forces[:,RM]/W
    present=n['rf_floor']
    native_in_opening=np.repeat(inside[:-1],80)[:len(hz)]
    loss=(native_in_opening&(hz<-.012)&(rf<.004))
    pre=np.flatnonzero(loss[:first+1])
    reloadable=(~native_in_opening)&(present[:,1]/W>=.02)
    reload=first_persistent(reloadable,30*80,start=first)
    if reload is None:
        raise ValueError('No sustained upper-floor landing outside the opening')
    early=first+200*80
    finish=first+435*80
    if min(len(forces),len(bn['forces']))<finish:
        raise ValueError('Unfinished support attribution window')
    other=forces[:,:6].sum(1)/W-rf
    no_rm=bn['forces'][:,RM]/W
    rm_delta=helper[first:finish]-no_rm[first:finish]
    rm_difference=helper[first:early]-no_rm[first:early]
    ideal=fn['forces'][:,RF]/W
    nom_at_missing=float(ideal[first:min(first+100*80,len(ideal))].mean())
    actions_pinned=np.array_equal(d['x'][:first_i+1],cd['x'][:first_i+1])
    prior_exact=all(np.array_equal(z[key][:first_ms+1],cz[key][:first_ms+1]) for key in ('qpos','qvel','loads','target'))
    can_change=np.zeros(action.shape[1],dtype=bool)
    can_change[RF_JOINTS]=True
    can_change[RM_JOINTS]=True
    rm_changed=np.max(np.abs(action[:,RM_JOINTS]),axis=1)>1e-11
    rf_changed=np.max(np.abs(action[:,RF_JOINTS]),axis=1)>1e-11
    reload_xyz=traj[min(len(traj)-1,(reload+79)//80)].tolist()
    # Retraction is a measured upward movement following loss, with subsequent load
    # generated by an upper floor contact in a different horizontal footprint.
    lowest_before_return=float(hz[max(0,first-50*80):reload].min())
    peak_before_return=float(hz[first:reload].max())
    checks=dict(full_native=bool(a['native_integrations']==904000),
                native_joint=bool(a['native_joint_pass']),
                sampled_joint=bool(r['joint_sampled_pass']),
                supported_filled_control=bool(fa['native_joint_pass'] and nom_at_missing>=.02),
                actual_unsupported_below_opening=bool(len(pre)>0),
                causal_after_loss=bool(len(pre)>0 and pre[0]<=first),
                exact_until_policy_intervention=bool(actions_pinned and prior_exact),
                scoped_full_body_correction=bool(np.isfinite(action).all() and np.abs(d['action']).max()<=1.0),
                both_groups_intervened=bool(rf_changed.any() and rm_changed.any()),
                higher_helper_than_retraction_only=bool(rm_delta.mean()>.008),
                enough_other_support=bool(np.mean(other[first:early])>.90 and other[first:early].min()>.75),
                real_retraction=bool(peak_before_return-lowest_before_return>.033),
                new_sustained_upper_floor_contact=True,
                no_extra_forces=bool(a['zero_extra_force']))
    result=dict(role=role,scope='frozen nominal body in one static shallow floor opening; RF recovery with current RM support',
                passed=all(checks.values()),checks=checks,run=str(run),control=str(control),
                filled_control=str(filled),retraction_only=str(ablation),
                result_sha256=stan.sha(run/'RESULT.json'),trace_sha256=r['trace_sha256'],
                decision_sha256=r['decision_sha256'],native_audit_sha256=r['native_audit_sha256'],
                initial_snapshot_sha256=r['initial_snapshot_sha256'],native_samples=a['native_integrations'],
                full_D1_D8=False, first_correction_ms=first_ms,first_observed_loss_native=int(pre[0]) if len(pre) else None,
                retraction_lowest_z=lowest_before_return,retraction_peak_z=peak_before_return,
                rf_first_upper_landing_native=int(reload),rf_first_upper_landing_ms=reload/80.,
                rf_upper_landing_xyz=reload_xyz,filled_after_expected_landing_mean_RF_W=nom_at_missing,
                gap_control_at_same_time_mean_RF_W=float(cn['forces'][first:first+100*80,RF].mean()/W),
                RM_positive_motor_rows=int(rm_changed.sum()),RF_motor_rows=int(rf_changed.sum()),
                other_support_min_W=float(other[first:early].min()),other_support_mean_W=float(other[first:early].mean()),
                RM_mean_increment_W_435ms=float(rm_delta.mean()),RM_mean_increment_W_200ms=float(rm_difference.mean()),
                RM_peak_increment_W=float(rm_delta.max()),ground_slide=a['max_ground_normalized_slip'],
                intervention_channels=np.flatnonzero(np.any(np.abs(action)>1e-11,axis=0)).tolist(),
                coordination_channels=np.flatnonzero(np.any(np.abs(action)>1e-11,axis=0)&~can_change).tolist(),
                scope_no_same_step_auxiliary=True,
                summed_observation_dimension=len(r['sensor_fields']))
    return result


if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('run',type=Path)
    p.add_argument('control',type=Path)
    p.add_argument('filled',type=Path)
    p.add_argument('ablation',type=Path)
    p.add_argument('--role',default='teacher')
    q=p.parse_args()
    r,c,f,a=(getattr(q,k).resolve() for k in ('run','control','filled','ablation'))
    result=compare(r,c,f,a,role=q.role)
    suffix='TEACHER_ACCEPTANCE.json' if q.role=='teacher' else 'STUDENT_ACCEPTANCE.json'
    stan.put(r/suffix,result)
    print(result)
    if not result['passed']:
        raise SystemExit(1)
