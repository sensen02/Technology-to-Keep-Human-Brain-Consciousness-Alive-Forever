"""Is the recorded connectome fragile to small per-neuron error?

Tests the claim "even 1% error per neuron, compounded with modelling error, is a
disaster". Connectivity structure (which edges exist) is never changed; only the
numerical strength of existing edges is perturbed, in two declared modes:

  per-edge   : each existing edge scaled by a log-normal draw
  per-neuron : each pre-synaptic neuron's whole output scaled by one draw

Both are seeded and reported per seed. Metrics are compared with the unperturbed
baseline on the identical real sensory replay, so differences are attributable to
the perturbation alone.
"""
import os
os.environ.setdefault('OPENBLAS_NUM_THREADS', '1')
os.environ.setdefault('MUJOCO_GL', 'egl')
import sys, json, time
from pathlib import Path
import numpy as np
from scipy import sparse

R = Path('/run/media/sensen/Data2/cell_wound_prototype')
BASE = R / 'experiments/s5-neural-translator/20261105T200021Z'
OUT = Path('/home/sensen/Desktop/engine修复验收/s5-neural-parameter-audit/20261106T022431Z')
sys.path[:0] = [str(BASE), str(R), str(R / 'tools')]
import runtime as rt
from engine.neural_cond import ConductanceNetwork, ConductanceParams

rt.O = OUT
rt.b.O = OUT
js, sha, dump = rt.js, rt.sha, rt.dump
AUD = Path('/home/sensen/Desktop/engine修复验收/s5-sensory-neural-audit/20261106T015244Z/neural/SENSORY_CURRENTS.npz')
NDT = .0005
STEPS = 1200
EDGE_SIGMAS = [0.001, 0.01, 0.05, 0.20]
NEURON_SIGMAS = [0.001, 0.01, 0.05, 0.20]
SEEDS = [1, 2, 3]


def arrays(p):
    with np.load(p) as z:
        return {k: z[k] for k in z.files}


def main():
    t0 = time.monotonic()
    run = rt.Runtime()
    cov = OUT / 'COVERAGE.json'
    if cov.exists():
        led = OUT / 'CLEANUP_LEDGER.json'
        d = js(led) if led.exists() else dict(importance='重要辅助', deleted=[])
        d['deleted'].append(dict(path=str(cov), sha256=sha(cov), bytes=cov.stat().st_size,
                                 classification='可再生临时',
                                 reason='Legacy dominant-count table regenerated by the constructor; unused here.'))
        seen = {}
        for e in d['deleted']:
            seen[(e['path'], e['sha256'])] = e
        d['deleted'] = list(seen.values())
        cov.unlink()
        dump(led, d)

    poolmat = sparse.csr_matrix(run.poolmat)
    matrix, limits = run.matrix, run.limits
    We = sparse.load_npz(rt.b.AB / 'A' / 'ACTUAL_We.npz').tocsr()
    Wi = sparse.load_npz(rt.b.AB / 'A' / 'ACTUAL_Wi.npz').tocsr()
    seq = np.repeat(arrays(AUD)['currents'].astype(np.float64), 2, axis=0)[:STEPS]
    assert seq.shape == (STEPS, 12000)

    def evaluate(we, wi):
        net = ConductanceNetwork(12000, ConductanceParams(), dt_ms=NDT * 1000)
        net.set_connectivity(we, wi)
        rates = np.zeros(66)
        decay = np.exp(-NDT / .005)
        torque = np.zeros((STEPS // 2, 42))
        # torque_sample placeholder to satisfy the linter in some environments
        total = 0
        cum = np.zeros(STEPS, np.int64)
        cells = np.zeros(12000, np.int64)
        for k in range(STEPS):
            sp = net.step(current_nA=seq[k])
            cells += sp
            n = int(sp.sum())
            total += n
            cum[k] = total
            rates = decay * rates + (1 - decay) * np.asarray(poolmat @ sp, float) / NDT
            if k % 2 == 1:
                torque[k // 2] = np.clip(limits / 100 * (matrix @ rates), -limits, limits)
        idx = np.arange(19, STEPS, 20)
        prev = np.concatenate([[0], cum[idx[:-1]]])
        wr = (cum[idx] - prev) / (20 * NDT) / 12000
        return dict(rate_mean_hz=float(wr.mean()), rate_std_hz=float(wr.std()), total=int(total),
                    active_cells=int(np.count_nonzero(cells)),
                    saturation=float(np.mean(np.abs(torque) >= (limits[None, :] - 1e-9))),
                    torque=torque)

    base = evaluate(We, Wi)
    ref = base['torque']
    ref_scale = float(np.mean(np.abs(ref))) + 1e-12

    def cmd_change(torque):
        return float(np.sqrt(np.mean((torque - ref) ** 2)) / ref_scale)

    def edge_noise(seed, sigma):
        rng = np.random.default_rng(seed)
        out = []
        for M in (We, Wi):
            n = M.copy()
            n.data = n.data * np.exp(rng.normal(0, sigma, M.nnz))
            out.append(n)
        return out

    def neuron_noise(seed, sigma):
        rng = np.random.default_rng(seed)
        out = []
        for M in (We, Wi):
            scale = np.exp(rng.normal(0, sigma, M.shape[0]))
            n = sparse.diags(scale) @ M
            n = sparse.csr_matrix(n)
            out.append(n)
        return out

    results = {'per_edge': {}, 'per_neuron': {}}
    for mode, gen, sigmas in [('per_edge', edge_noise, EDGE_SIGMAS), ('per_neuron', neuron_noise, NEURON_SIGMAS)]:
        for sigma in sigmas:
            rows = []
            for seed in SEEDS:
                we, wi = gen(seed, sigma)
                res = evaluate(we, wi)
                rows.append(dict(seed=seed, rate_mean_hz=res['rate_mean_hz'], rate_std_hz=res['rate_std_hz'],
                                 rate_change_fraction=float(res['rate_mean_hz'] / base['rate_mean_hz'] - 1.0),
                                 active_cells=res['active_cells'], total_spikes=res['total'],
                                 spike_count_change_fraction=float(res['total'] / base['total'] - 1.0),
                                 saturation=res['saturation'], cmd_relative_rms_change=cmd_change(res['torque'])))
            results[mode][f'sigma_{sigma:g}'] = dict(
                sigma=sigma, per_seed=rows,
                rate_change_range=[min(r['rate_change_fraction'] for r in rows), max(r['rate_change_fraction'] for r in rows)],
                spike_change_range=[min(r['spike_count_change_fraction'] for r in rows), max(r['spike_count_change_fraction'] for r in rows)],
                cmd_change_range=[min(r['cmd_relative_rms_change'] for r in rows), max(r['cmd_relative_rms_change'] for r in rows)],
                saturation_range=[min(r['saturation'] for r in rows), max(r['saturation'] for r in rows)])

    # Structural note: how many edges and neurons does a 1% per-neuron draw actually touch?
    nnz = int(We.nnz + Wi.nnz)
    verdict = dict(
        stage='fragility of the recorded connectome to small per-neuron error', importance='核心必需',
        baseline=dict(rate_mean_hz=base['rate_mean_hz'], rate_std_hz=base['rate_std_hz'],
                      active_cells=base['active_cells'], total_spikes=base['total'], saturation=base['saturation']),
        modes=results,
        graph=dict(We_nnz=int(We.nnz), Wi_nnz=int(Wi.nnz), edges=nnz, neurons=12000,
                   note='Edge existence is never changed in this test; only strength, so the connectome structure '
                        'remains the recorded one.'),
        interpretation='Quantifies how much the driven response moves when each recorded strength is off by a '
                       'stated amount. This bounds sensitivity to model error; it does not measure the real error of '
                       'the connectome, which has no ground truth in this project.',
        boundaries=['1200-step replay, single real sensory segment', 'strength perturbation only, structure fixed',
                    'no behavioural scoring here', 'absolute forces and SI remain NOT_ESTABLISHED'])
    dump(OUT / 'CONNECTOME_FRAGILITY.json', verdict)
    for mode in ['per_edge', 'per_neuron']:
        for key, v in results[mode].items():
            print(f"{mode:11s} {key:12s} rate_change={v['rate_change_range']} cmd={v['cmd_change_range']} sat={v['saturation_range']}", flush=True)
    print('WALL_S', time.monotonic() - t0, flush=True)


if __name__ == '__main__':
    main()
